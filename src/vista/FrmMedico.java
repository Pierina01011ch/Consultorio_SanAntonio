    private void MostrarMedicos() {

    try {

        ConexionBD conexionBD = new ConexionBD();
        Connection con = conexionBD.conectar();

        String sql = "SELECT * FROM medico";

        PreparedStatement ps = con.prepareStatement(sql);

        ResultSet rs = ps.executeQuery();

        DefaultTableModel modelo = new DefaultTableModel();

        modelo.addColumn("ID");
        modelo.addColumn("Nombre");
        modelo.addColumn("Apellido");
        modelo.addColumn("CMP");
        modelo.addColumn("Especialidad");
        modelo.addColumn("Teléfono");
        modelo.addColumn("Horario");

        while (rs.next()) {

            modelo.addRow(new Object[]{
                rs.getInt("idMedico"),
                rs.getString("nombre"),
                rs.getString("apellido"),
                rs.getString("cmp"),
                rs.getString("especialidad"),
                rs.getString("telefono"),
                rs.getString("horario")
            });

        }

        tblMedicos.setModel(modelo);
        
        tblMedicos.getColumnModel().getColumn(0).setPreferredWidth(40);
        tblMedicos.getColumnModel().getColumn(0).setMaxWidth(50);
        tblMedicos.getColumnModel().getColumn(0).setMinWidth(40);

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage());

    }

}

