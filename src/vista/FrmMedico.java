    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {

    ConexionBD conexionBD = new ConexionBD();
    Connection con = conexionBD.conectar();

    String sql =
        "INSERT INTO medico "
      + "(nombre, apellido, cmp, especialidad, telefono, horario) "
      + "VALUES (?, ?, ?, ?, ?, ?)";

    PreparedStatement ps =
            con.prepareStatement(sql);

    ps.setString(1, txtNombre.getText());
    ps.setString(2, txtApellido.getText());
    ps.setString(3, txtCmp.getText());
    ps.setString(4, txtEspecialidad.getText());
    ps.setString(5, txtTelefono.getText());
    ps.setString(6, txtHorario.getText());

    ps.executeUpdate();

    JOptionPane.showMessageDialog(this, "Médico registrado correctamente");

    MostrarMedicos();
    LimpiarCampos();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "Error: " + e.getMessage());

}
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {

        ConexionBD conexionBD = new ConexionBD();
        Connection con = conexionBD.conectar();

        String sql = "SELECT * FROM medico WHERE cmp = ?";

        PreparedStatement ps = con.prepareStatement(sql);

        ps.setString(1, txtCmp.getText());

        ResultSet rs = ps.executeQuery();

        if (rs.next()) {

            txtNombre.setText(rs.getString("nombre"));
            txtApellido.setText(rs.getString("apellido"));
            txtEspecialidad.setText(rs.getString("especialidad"));
            txtTelefono.setText(rs.getString("telefono"));
            txtHorario.setText(rs.getString("horario"));

        } else {

            JOptionPane.showMessageDialog(this, "Médico no encontrado");

        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());

    }         
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        try {

        ConexionBD conexionBD = new ConexionBD();
        Connection con = conexionBD.conectar();

        String sql = "UPDATE medico SET "
                + "nombre = ?, "
                + "apellido = ?, "
                + "especialidad = ?, "
                + "telefono = ?, "
                + "horario = ? "
                + "WHERE cmp = ?";

        PreparedStatement ps = con.prepareStatement(sql);

        ps.setString(1, txtNombre.getText());
        ps.setString(2, txtApellido.getText());
        ps.setString(3, txtEspecialidad.getText());
        ps.setString(4, txtTelefono.getText());
        ps.setString(5, txtHorario.getText());

        ps.setString(6, txtCmp.getText());

        int filas = ps.executeUpdate();

        if (filas > 0) {

            JOptionPane.showMessageDialog(this, "Médico actualizado correctamente");

            MostrarMedicos();
            LimpiarCampos();

        } else {

            JOptionPane.showMessageDialog(this, "No existe un médico con ese CMP");
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try {

        int opcion = JOptionPane.showConfirmDialog(
                this,
                "¿Desea eliminar este médico?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION);

        if (opcion != JOptionPane.YES_OPTION) {
            return;
        }

        ConexionBD conexionBD = new ConexionBD();
        Connection con = conexionBD.conectar();

        String sql = "DELETE FROM medico WHERE cmp = ?";

        PreparedStatement ps = con.prepareStatement(sql);

        ps.setString(1, txtCmp.getText());

        int filas = ps.executeUpdate();

        if (filas > 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Médico eliminado correctamente");

            MostrarMedicos();
            LimpiarCampos();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No existe un médico con ese CMP");
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
}
    }//GEN-LAST:event_btnEliminarActionPerformed

